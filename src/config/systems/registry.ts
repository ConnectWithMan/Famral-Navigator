export function getSystemConfig(code: string): CounsellingSystemConfig | undefined {
  return COUNSELLING_SYSTEMS.find((s) => s.code.toLowerCase() === code.toLowerCase());
}

export function getActiveSystems(): CounsellingSystemConfig[] {
  return COUNSELLING_SYSTEMS.filter((s) => s.status === 'active');
}

export function getLatestRoundNumber(system: CounsellingSystemConfig | undefined): number {
  if (!system || system.rounds.length === 0) return 1;
  return system.rounds[system.rounds.length - 1].number;
}

export function getEffectiveCategory(
  system: CounsellingSystemConfig,
  baseCategory: string,
  isPwd: boolean
): string {
  const clean = baseCategory.trim();
  if (!isPwd) return clean;
  if (clean.endsWith(system.pwdSuffix)) return clean;
  return `${clean}${system.pwdSuffix}`;
}

export function getExpectedRankType(
  system: CounsellingSystemConfig,
  effectiveCategory: string
): 'CRL' | 'CATEGORY_RANK' {
  return system.rankTypeByCategory[effectiveCategory] ?? system.defaultRankType;
}
